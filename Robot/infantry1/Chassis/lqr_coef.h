static constexpr float kBetaCoefficients[4] = {-3.030821085e-01f, 2.273112535e+00f, -7.241505623e+00f, 8.601252556e+00f};
inline float clampLength(float length) {
    return std::fmax(kLowerLength, std::fmin(kUpperLength, length));
}
inline float normalize(float length) {
    return std::fmax(-1.0f, std::fmin(1.0f, (length-kLengthCenter)/kLengthScale));
}
inline void evaluateGain(float L1, float L2, float (&gain)[kInputDim][kStateDim]) {
    const float x = normalize(L1), y = normalize(L2);
    for (int i=0; i<kInputDim; ++i) for (int j=0; j<kStateDim; ++j) {
        float value = 0.0f;
        for (int a=kDegree; a>=0; --a) {
            float row = 0.0f;
            for (int b=kDegree; b>=0; --b) row = row*y + kGainCoefficients[i][j][a][b];
            value = value*x + row;
        }
        gain[i][j] = value;
    }
}
inline float evaluateBeta(float length) {
    length = clampLength(length);
    float beta = 0.0f;
    for (int a=kBetaDegree; a>=0; --a) beta = beta*length + kBetaCoefficients[a];
    return beta;
}
inline void evaluateTrim(float L1, float L2, float (&state)[kStateDim], float (&input)[kInputDim]) {
    const float x = normalize(L1), y = normalize(L2);
    for (int i=0; i<kStateDim; ++i) state[i] = 0.0f;
    state[6] = evaluateBeta(L1); state[8] = evaluateBeta(L2);
    for (int i=0; i<kInputDim; ++i) {
        float value = 0.0f;
        for (int a=kDegree; a>=0; --a) {
            float row = 0.0f;
            for (int b=kDegree; b>=0; --b) row = row*y + kInputCoefficients[i][a][b];
            value = value*x + row;
        }
        input[i] = value;
    }
}
// Passive generalized force along increasing leg length, in N.
inline float evaluateGasSpringForce(float length) {
    const float x = std::fmax(-1.0f, std::fmin(1.0f,
        (length-kGasSpringLengthCenter)/kGasSpringLengthScale));
    float force = 0.0f;
    for (int i=kGasSpringDegree; i>=0; --i) force = force*x + kGasSpringForceCoefficients[i];
    return force;
}
// Complete motor-side U0: [Tw1,Tw2,Tp1,Tp2,FL1,FL2].
// FL already includes spring cancellation. Do not subtract it again.
inline void evaluateFeedforward(float L1, float L2, float (&state)[kStateDim],
                                float (&u0)[kFeedforwardDim], float springScale=1.0f) {
    float torque[kInputDim];
    evaluateTrim(L1, L2, state, torque);
    for (int i=0; i<kInputDim; ++i) u0[i] = torque[i];
    u0[4] = kSupportForcePerLeg - springScale*evaluateGasSpringForce(L1);
    u0[5] = kSupportForcePerLeg - springScale*evaluateGasSpringForce(L2);
}
